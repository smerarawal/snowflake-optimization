USE SCHEMA QSS_SNOWFLAKE_LAB.RAW;

CREATE OR REPLACE TABLE DIM_TENANT (TENANT_ID VARCHAR, TENANT_NAME VARCHAR, REGION VARCHAR,
  TIMEZONE VARCHAR, QUEUE_ENABLED NUMBER, STAFF_CAPACITY NUMBER, CREATED_AT TIMESTAMP_NTZ);
CREATE OR REPLACE TABLE DIM_SERVICE (SERVICE_ID NUMBER, TENANT_ID VARCHAR, CATEGORY VARCHAR,
  AVG_DURATION_MIN NUMBER);
CREATE OR REPLACE TABLE APPOINTMENTS (APPOINTMENT_ID NUMBER, TENANT_ID VARCHAR, SERVICE_ID NUMBER,
  CUSTOMER_ID NUMBER, STATUS VARCHAR, CREATED_AT TIMESTAMP_NTZ, SCHEDULED_AT TIMESTAMP_NTZ,
  CHECKED_IN_AT TIMESTAMP_NTZ, COMPLETED_AT TIMESTAMP_NTZ, CANCELLED_AT TIMESTAMP_NTZ,
  UPDATED_AT TIMESTAMP_NTZ, INGESTED_AT TIMESTAMP_NTZ);
CREATE OR REPLACE TABLE QUEUE_EVENTS (EVENT_ID NUMBER, APPOINTMENT_ID NUMBER, TENANT_ID VARCHAR,
  EVENT_TYPE VARCHAR, EVENT_TS TIMESTAMP_NTZ, COUNTER_ID NUMBER, INGESTED_AT TIMESTAMP_NTZ);
CREATE OR REPLACE TABLE NOTIFICATIONS (NOTIFICATION_ID NUMBER, APPOINTMENT_ID NUMBER, TENANT_ID VARCHAR,
  MESSAGE_TYPE VARCHAR, CHANNEL VARCHAR, ATTEMPT_NO NUMBER, RETRY_COUNT NUMBER,
  DELIVERY_STATUS VARCHAR, CREATED_AT TIMESTAMP_NTZ, INGESTED_AT TIMESTAMP_NTZ);
CREATE OR REPLACE TABLE AUDIT_EVENTS (AUDIT_ID NUMBER, TENANT_ID VARCHAR, ENTITY_TYPE VARCHAR,
  ENTITY_ID NUMBER, EVENT_TYPE VARCHAR, ACTOR_TYPE VARCHAR, EVENT_TS TIMESTAMP_NTZ,
  INGESTED_AT TIMESTAMP_NTZ);
-- Note: no clustering keys on purpose; Experiment 3 tests whether clustering pays off.
-- Tables are loaded in generation order, i.e. NOT sorted by created_at, so pruning on
-- created_at is a genuine test rather than a freebie.
